import { existsSync, watch } from "node:fs";
import { rename } from "node:fs/promises";
import { basename, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import "./app-platform";

const backendDir = fileURLToPath(new URL("../../backend/", import.meta.url));
const sourceDir = resolve(backendDir, "convex");
const { default: ts } = await import("typescript");
const generated = "// Generated by bun run generate:platforms.";
const glob = new Bun.Glob("**/*.{ts,tsx,js,jsx,mts,cts,mjs,cjs}");

function isFunctionSource(path: string) {
  const name = basename(path);
  if (path.startsWith("_generated") || path.includes(" ") || /^[.#]/.test(name) ||
      /^schema\.(ts|js)$/.test(name) || name.split(".").length !== 2) return false;
  for (let dir = dirname(path); dir !== "."; dir = dirname(dir)) {
    if (existsSync(resolve(sourceDir, dir, "convex.config.ts"))) return false;
  }
  return true;
}

async function writeGenerated(path: string, source: string) {
  const output = Bun.file(path);
  if (await output.exists()) {
    const current = await output.text();
    if (current === source) return;
    if (!current.startsWith(generated)) {
      throw new Error(`Move ${path} before generating platform code. This path is reserved for the kit.`);
    }
  }
  const temporary = path + `.${process.pid}.tmp`;
  await Bun.write(temporary, source);
  await rename(temporary, path);
}

async function generate() {
  await writeGenerated(resolve(sourceDir, "app.ts"), `${generated}\nexport { features } from "@disposabl-kit/server/features.ts";\n`);
  const imports: string[] = [];
  const entries: string[] = [];
  for (const name of [...glob.scanSync(sourceDir)].sort()) {
    if (!isFunctionSource(name)) continue;
    const source = ts.createSourceFile(name, await Bun.file(resolve(sourceDir, name)).text(), ts.ScriptTarget.Latest, true);
    const module = name.replaceAll("\\", "/").replace(/\.[^.]+$/, "");
    for (const statement of source.statements) {
      if (!ts.isVariableStatement(statement) || !statement.modifiers?.some(m => m.kind === ts.SyntaxKind.ExportKeyword)) continue;
      for (const { name, initializer } of statement.declarationList.declarations) {
        if (!ts.isIdentifier(name) || !initializer || !ts.isCallExpression(initializer)) continue;
        const options = initializer.arguments[0];
        if (!options || !ts.isObjectLiteralExpression(options) || !options.properties.some(property =>
          ts.isPropertyAssignment(property) && (ts.isIdentifier(property.name) || ts.isStringLiteral(property.name)) &&
          property.name.text === "platforms" && property.initializer.kind === ts.SyntaxKind.TrueKeyword
        )) continue;
        const node = source.statements.some(statement => ts.isExpressionStatement(statement) &&
          ts.isStringLiteral(statement.expression) && statement.expression.text === "use node");
        if (node) throw new Error(`${module}:${name.text} must call its Node action from an opted-in default-runtime action`);
        const id = `${module}:${name.text}`;
        const alias = `operation${entries.length}`;
        imports.push(`import { ${name.text} as ${alias} } from ${JSON.stringify("./convex/" + module)};`);
        entries.push(`  ${JSON.stringify(id)}: ${alias},`);
      }
    }
  }
  const registry = [generated, ...imports, "export default {", ...entries, "};", ""].join("\n");
  await writeGenerated(resolve(backendDir, "platforms.generated.ts"), registry);
}

await generate();
if (process.argv[2] === "dev") {
  let queued: NodeJS.Timeout | undefined;
  let running = Promise.resolve();
  const watcher = watch(sourceDir, { recursive: true }, (_, name) => {
    if (!name || name.startsWith("_generated/") || !/\.[cm]?[tj]sx?$/.test(name)) return;
    clearTimeout(queued);
    queued = setTimeout(() => {
      running = running.then(generate).catch(error => console.error(error));
    }, 50);
  });
  const convex = Bun.spawn(["bun", "run", "convex", "dev", ...process.argv.slice(3)], {
    cwd: backendDir, stdin: "inherit", stdout: "inherit", stderr: "inherit",
  });
  for (const signal of ["SIGINT", "SIGTERM"] as const) process.on(signal, () => convex.kill(signal));
  process.exitCode = await convex.exited;
  watcher.close();
  clearTimeout(queued);
  await running;
}
