import { rename } from "node:fs/promises";
import { fileURLToPath } from "node:url";

export const convex = fileURLToPath(new URL("../../backend/convex/", import.meta.url));
const registryUrl = new URL("./generated/platforms.ts", import.meta.url);
const registry = Bun.file(registryUrl);
const candidates = new Bun.Glob("**/*.{ts,tsx,js,jsx,mts,mjs,cts,cjs}");

function isFunctionSource(path: string) {
  return !path.startsWith("_generated/") &&
    !/\.d\.[cm]?ts$/.test(path) &&
    !path.split("/").some((part) => part.startsWith(".") || part.startsWith("#"));
}

export async function generatePlatforms() {
  const imports: string[] = [];
  const modules: string[] = [];
  for (const path of [...candidates.scanSync(convex)].filter(isFunctionSource).sort()) {
    const source = await Bun.file(convex + path).text();
    if (!/(?:\bplatforms|["']platforms["'])\s*:\s*true\b/.test(source)) continue;
    if (/^\s*["']use node["']/.test(source)) {
      throw new Error(`${path}: expose a default-runtime internal action that calls the Node action`);
    }
    const module = `m${modules.length}`;
    const name = path.replace(/\.[^.]+$/, "");
    imports.push(`import * as ${module} from ${JSON.stringify("../../../backend/convex/" + name)};`);
    modules.push(`  ${JSON.stringify(name)}: ${module},`);
  }
  const source = [
    "// Generated by bun run generate:platforms.",
    ...imports,
    "",
    "export default {",
    ...modules,
    "};",
    "",
  ].join("\n");
  if (!(await registry.exists()) || (await registry.text()) !== source) {
    const staged = new URL(`./generated/platforms-${process.pid}.tmp`, import.meta.url);
    await Bun.write(staged, source);
    await rename(staged, registryUrl);
  }
}

if (import.meta.main) await generatePlatforms();
