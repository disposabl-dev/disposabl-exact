import { getPlatformValidators } from "@disposabl-kit/server";
import { mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const convex = new URL("./convex/", import.meta.url);
const generated = new URL("./generated/", import.meta.url);
const entries: string[] = [];
const modules = new Map<string, string>();

const paths = [
  ...new Bun.Glob("**/*.ts").scanSync(fileURLToPath(convex)),
].sort();
for (const path of paths) {
  if (path.startsWith("_generated/") || path.endsWith(".d.ts")) continue;
  const url = new URL(path, convex);
  const source = await Bun.file(url).text();
  if (
    path !== "internal.ts" &&
    !path.endsWith("/internal.ts") &&
    !/\bplatforms\s*:\s*true\b/.test(source)
  )
    continue;

  const functions: Record<string, unknown> = await import(url.href);
  const moduleName = path.slice(0, -3);
  for (const name of Object.keys(functions).sort()) {
    const fn = functions[name] as {
      platforms?: true;
      isInternal?: boolean;
      isQuery?: boolean;
      isMutation?: boolean;
      isAction?: boolean;
    } | null;
    if (fn?.platforms !== true) continue;
    const id = `${moduleName}:${name}`;
    const kind = fn.isQuery
      ? "query"
      : fn.isMutation
        ? "mutation"
        : fn.isAction
          ? "action"
          : null;
    if (!fn.isInternal || !kind)
      throw new Error(
        `${id}: use an internal builder from @disposabl-kit/server`,
      );
    if (/^\s*["']use node["']/.test(source))
      throw new Error(
        `${id}: expose a default-runtime internal action that calls this Node action`,
      );
    getPlatformValidators(fn, id);
    const module = modules.get(moduleName) ?? `m${modules.size}`;
    modules.set(moduleName, module);
    const reference = [...moduleName.split("/"), name]
      .map((part) => `[${JSON.stringify(part)}]`)
      .join("");
    entries.push(
      `  ${JSON.stringify(id)}: {\n    kind: "${kind}",\n    reference: internal${reference},\n    ...getPlatformValidators(${module}[${JSON.stringify(name)}], ${JSON.stringify(id)}),\n  },\n`,
    );
  }
}

const output = Bun.file(new URL("platforms.ts", generated));
const source =
  "// Generated by bun run generate:platforms.\n" +
  `import { ${entries.length ? "getPlatformValidators, " : ""}type PlatformDefinition } from "@disposabl-kit/server";\n` +
  (entries.length
    ? 'import { internal } from "../convex/_generated/api";\n' +
      [...modules]
        .map(
          ([path, name]) =>
            `import * as ${name} from ${JSON.stringify("../convex/" + path)};\n`,
        )
        .join("") +
      "\n"
    : "") +
  `export default {${entries.length ? "\n" + entries.join("") : ""}} satisfies Record<string, PlatformDefinition>;\n`;
if (!(await output.exists()) || (await output.text()) !== source) {
  await mkdir(generated, { recursive: true });
  await Bun.write(output, source);
}
