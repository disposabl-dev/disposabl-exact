import { convexToZodFields } from "convex-helpers/server/zod4";
import type { PropertyValidators } from "convex/values";
import { mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import * as z from "zod/v4";

const convex = new URL("./convex/", import.meta.url);
const generated = new URL("./generated/", import.meta.url);
const entries: string[] = [];

const paths = [
  ...new Bun.Glob("**/*.ts").scanSync(fileURLToPath(convex)),
].sort();
for (const path of paths) {
  if (path.startsWith("_generated/") || path.endsWith(".d.ts")) continue;
  const source = Bun.file(new URL(path, convex));
  if (
    path !== "internal.ts" &&
    !path.endsWith("/internal.ts") &&
    !/\bplatforms\s*:\s*true\b/.test(await source.text())
  )
    continue;

  const functions: Record<string, unknown> = await import(
    new URL(path, convex).href
  );
  const moduleName = path.slice(0, -3);
  for (const name of Object.keys(functions).sort()) {
    const fn = functions[name] as {
      platforms?: true;
      platformArgs?: PropertyValidators;
      isInternal?: boolean;
      isQuery?: boolean;
      isMutation?: boolean;
      isAction?: boolean;
    } | null;
    if (fn?.platforms !== true) continue;
    const id = `${moduleName}:${name}`;
    const kind = fn.isQuery
      ? "query"
      : fn.isMutation
        ? "mutation"
        : fn.isAction
          ? "action"
          : null;
    if (!fn.isInternal || !kind || !fn.platformArgs)
      throw new Error(
        `${id}: use an internal builder from @disposabl-kit/server`,
      );
    const inputSchema = z.toJSONSchema(
      z.strictObject(convexToZodFields(fn.platformArgs)),
    );
    const reference = [...moduleName.split("/"), name]
      .map((part) => `[${JSON.stringify(part)}]`)
      .join("");
    const schema = JSON.stringify(inputSchema, null, 2).replaceAll(
      "\n",
      "\n    ",
    );
    entries.push(
      `  ${JSON.stringify(id)}: {\n    kind: "${kind}",\n    reference: internal${reference},\n    inputSchema: ${schema},\n  },\n`,
    );
  }
}

const output = Bun.file(new URL("platforms.ts", generated));
const source =
  "// Generated by bun run generate:platforms.\n" +
  'import type { PlatformDefinition } from "@disposabl-kit/server";\n' +
  (entries.length
    ? 'import { internal } from "../convex/_generated/api";\n\n'
    : "") +
  `export default {${entries.length ? "\n" + entries.join("") : ""}} satisfies Record<string, PlatformDefinition>;\n`;
if (!(await output.exists()) || (await output.text()) !== source) {
  await mkdir(generated, { recursive: true });
  await Bun.write(output, source);
}
